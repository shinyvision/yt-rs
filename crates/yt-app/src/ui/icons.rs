/// Writes the icons and adds them to the display's icon theme.
pub fn install(display: &gdk::Display) {
    let root = yt_core::paths::cache_dir().join("icons");
    let dir = root.join("hicolor/scalable/actions");
    if std::fs::create_dir_all(&dir).is_err() {
        return;
    }
    for (name, path, flipped) in ICONS {
        let transform = if *flipped {
            r#" transform="rotate(180 12 12)""#
        } else {
            ""
        };
        let svg = format!(
            r##"<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24"><path fill="#bebebe"{transform} d="{path}"/></svg>"##
        );
        let file = dir.join(format!("{name}.svg"));
        if std::fs::read_to_string(&file).ok().as_deref() != Some(svg.as_str()) {
            let _ = std::fs::write(&file, svg);
        }
    }
    gtk::IconTheme::for_display(display).add_search_path(root);
}
